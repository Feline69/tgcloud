  var _lang = 'en';

  function detect() {
    try { var s = localStorage.getItem('lang'); if (s && LANGS[s]) return s; } catch(e){}
    var b = (navigator.language || '').toLowerCase();
    if (b.startsWith('es')) return 'es';
    if (b.startsWith('pt')) return 'pt';
    return 'en';
  }

  function t(key, vars) {
    var dict = LANGS[_lang] || LANGS.en;
    var str = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : (LANGS.en[key] !== undefined ? LANGS.en[key] : key);
    if (vars) {
      for (var k in vars) {
        if (Object.prototype.hasOwnProperty.call(vars, k)) {
          str = str.split('{' + k + '}').join(String(vars[k]));
        }
      }
    }
    return str;
  }

  function setLang(lang) {
    if (!LANGS[lang]) return;
    _lang = lang;
    try { localStorage.setItem('lang', lang); } catch(e){}
    document.documentElement.lang = lang;
    document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  }

  function getLang() { return _lang; }
  function getLangs() { return Object.keys(LANGS); }

  _lang = detect();
  document.documentElement.lang = _lang;

  window.t = t;
  window.setLang = setLang;
  window.getLang = getLang;
  window.getLangs = getLangs;
